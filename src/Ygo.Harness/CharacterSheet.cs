using System.Text;
using System.Text.Json;
using Ygo.Engine.AI;
using Ygo.Engine.Campaign;

namespace Ygo.Harness;

/// <summary>
/// `--characters <out.md>`: every duelist as a Markdown list, grouped the way the campaign meets them (band by band,
/// then the free-play-only regulars): name and title, play style and skill, decks (with their era and standing for the
/// historic ones), their opening line, and what they look like.
/// </summary>
public static class CharacterSheet
{
    public static int Run(string root, string output)
    {
        var roster = Personality.LoadFolder(Path.Combine(root, "personalities"));
        var circuits = Circuits.Load(Path.Combine(root, "campaign", "circuits.txt"), roster);
        using var catalog = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "campaign", "history.json")));
        var history = catalog.RootElement.EnumerateArray().ToDictionary(e => e.GetProperty("id").GetString()!, e => e);

        string Deck(string id) => history.TryGetValue(id, out var h)
            ? $"{h.GetProperty("name").GetString()} ({h.GetProperty("year").GetInt32()}, {h.GetProperty("tier").GetString()})"
            : id switch
            {
                "classic" => "Legendary Dragons (Blue-Eyes, Dark Magician, early classics)",
                "warriors" => "Warrior's Charge (warrior beatdown)",
                "zombies" => "Undead Legion (zombies that come back)",
                "gadgets" => "Gadgets (Red, Green and Yellow Gadget machines)",
                "stall-burn" => "Stall and burn (walls, then damage effects)",
                "synchron" => "Synchron (Junk Synchron Synchro climbing)",
                "modern" => "Modern (a current-day staple build)",
                _ => id,
            };

        // When the campaign first meets each character.
        var met = new List<(string band, Personality who)>();
        foreach (var c in circuits.All)
            foreach (var m in c.Matches)
                if (!met.Any(x => x.who.Id == m.Character.Id)) met.Add((c.Band, m.Character));
        var rest = roster.Where(p => !met.Any(x => x.who.Id == p.Id)).OrderBy(p => p.Name).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("# Duel Circuit: the duelists");
        sb.AppendLine();
        sb.AppendLine($"{roster.Count} fictional duelists, in the order the campaign introduces them. Skill is out of 10 (9 and up plan their");
        sb.AppendLine("turns ahead; 7 and up know their deck's combos). Generated by `--characters` from `personalities/` and `campaign/history.json`.");
        void Write(Personality p)
        {
            sb.AppendLine();
            sb.AppendLine($"### {p.DisplayName}");
            if (File.Exists(Path.Combine(root, "art", "portraits", p.Id + ".png")))
                sb.AppendLine($"<img src=\"../art/portraits/{p.Id}.png\" alt=\"{p.Name}\" height=\"180\">");
            sb.AppendLine($"- **Style:** {p.StyleSummary}");
            sb.AppendLine($"- **Decks:** {string.Join("; ", p.Decks.Select(Deck))}");
            if (p.Intro.Length > 0) sb.AppendLine($"- **Says:** \"{p.Intro}\"");
            if (p.Look.Length > 0) sb.AppendLine($"- **Looks:** {p.Look}");
        }
        foreach (var band in met.Select(x => x.band).Distinct())
        {
            sb.AppendLine();
            sb.AppendLine($"## {band}");
            foreach (var (_, who) in met.Where(x => x.band == band)) Write(who);
        }
        if (rest.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Outside the circuits (free play and the ladder)");
            foreach (var p in rest) Write(p);
        }
        File.WriteAllText(output, sb.ToString());
        Console.WriteLine($"Wrote {roster.Count} duelists to {output}");
        return 0;
    }
}
